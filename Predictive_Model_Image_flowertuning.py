from tensorflow.keras.layers import Dense, GlobalAveragePooling2D
from tensorflow.keras.models import Model


def create_model1(num_classes=10):
  """Takes a TensorFlow Hub URL and creates a Keras Sequential model with it.

  Args:
    model_url (str): A TensorFlow Hub feature extraction URL.
    num_classes (int): Number of output neurons in output layer,
      should be equal to number of target classes, default 10.

  Returns:
    An uncompiled Keras Sequential model with model_url as feature
    extractor layer and Dense output layer with num_classes outputs.
  """
  base_model = MobileNetV2(weights='imagenet', include_top=False, input_shape=(224, 224, 3))
  base_model.trainable = False

  x = base_model.output
  x = GlobalAveragePooling2D()(x)  # Reduce las dimensiones a una capa plana
  x = Dense(1024, activation='relu')(x)  # Añadir una capa completamente conectada
  predictions = Dense(num_classes, activation='softmax')(x)  # Cambia '10' por el número de clases que tengas

# Definir el modelo completo
  model = Model(inputs=base_model.input, outputs=predictions)
  return model



