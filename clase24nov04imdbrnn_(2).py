import tensorflow as tf
from tensorflow.keras.datasets import imdb
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Embedding, LSTM, GRU, Dense, Conv1D, MaxPooling1D, Dropout, Flatten, Input
from tensorflow.keras.preprocessing.sequence import pad_sequences

# Commented out IPython magic to ensure Python compatibility.
# %load_ext tensorboard

"""#Obtener datos
Base de datos de IMDB, con texto ya en formato numerico y
"""

# Cargar el dataset IMDB
max_features = 10000  # Número de palabras más frecuentes en el vocabulario
(x_train, y_train), (x_test, y_test) = imdb.load_data(num_words=max_features)

"""##Preprocesamiento"""

max_len = 200
x_train = pad_sequences(x_train, maxlen=max_len)
x_test = pad_sequences(x_test, maxlen=max_len)

"""##Entrenamiento

### Multiperceptron
"""

model_1= Sequential([
    Input(shape=(max_len,)),
    Dense(32, activation='relu'),
    Dense(1, activation='sigmoid')  # Clasificación binaria
  ]
)
model_1.summary()

tensorboard_callback = tf.keras.callbacks.TensorBoard(log_dir="./logs", histogram_freq=1)
model_1.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])
model_1.fit(x_train, y_train, epochs=5, batch_size=64, validation_data=(x_test, y_test),
            callbacks=[tensorboard_callback]) #callback para TensorBoard

"""### Multiperceptron con Dropout"""

model_1_5= Sequential([
    Input(shape=(max_len,)),
    Dropout(0.5),
    Dense(32, activation='relu'),
    Dropout(0.5),
    Dense(1, activation='sigmoid')  # Clasificación binaria
  ]
)
model_1_5.summary()

tensorboard_callback_2 = tf.keras.callbacks.TensorBoard(log_dir="./logs", histogram_freq=1)

model_1_5.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])
model_1_5.fit(x_train, y_train, epochs=5, batch_size=64, validation_data=(x_test, y_test),
            callbacks=[tensorboard_callback_2]) #callback para TensorBoard

"""### Multipercpetron con Embedding

"""

embedding_dim = 128
model_2= Sequential([
    Input(shape=(max_len,)),
    Embedding(input_dim=max_features, output_dim=embedding_dim),
    Flatten(),
    Dropout(0.5),
    Dense(32, activation='relu'),
    Dropout(0.5),
    Dense(1, activation='sigmoid')  # Clasificación binaria
  ]
)
model_2.summary()

model_2.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])
model_2.fit(x_train, y_train, epochs=5, batch_size=64, validation_data=(x_test, y_test),
            callbacks=[tensorboard_callback]) #callback para TensorBoard

