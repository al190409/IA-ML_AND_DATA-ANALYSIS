class Simulador:
  def __init__(self,numSim):
    self.duracion=0
    self.a=0
    self.x0=0
    self.v0=0
    self.numSimulaciones=numSim
    self.ejex=[]
    self.ejey=[]
    self.idSim=[]

  def setParam(self,duracion,a,x0,v0):
    self.duracion=duracion
    self.a=a
    self.x0=x0
    self.v0=v0

  def calcular(self,t):
    return self.x0+self.v0*t+(0.5)*self.a*t**2 #xf(t)

  def simular(self):
    for j in range(self.numSimulaciones):
      d=int(input('Escribe la duración de la simulación:'))
      a=float(input('Escribe el valor de la aceleración:'))
      x0=float(input('Escribe la posición inicial:'))
      v0=float(input('Escribe la velocidad inicial:'))
      self.setParam(d,a,x0,v0)

      for i in range(self.duracion+1):
        self.ejex.append(i)
        self.ejey.append(self.calcular(i))
        self.idSim.append(j)

      #print(self.ejex)
      #print(self.ejey)

  def graficar(self):
    pyplot.scatter(self.ejex,self.ejey,c=self.idSim)
    pyplot.ylabel('Posición (m)')
    pyplot.xlabel('Tiempo (s)')
    pyplot.title("Gráfica Posición / Tiempo")
    pyplot.grid()
    pyplot.show()

  def escribir(self):
    f=open('datos.csv','w')
    f.write('idSim,t,posicion\n')
    for i in range(len(self.ejex)):
     f.write('{},{},{}\n'.format(self.idSim[i],self.ejex[i],self.ejey[i]))
    f.close()

